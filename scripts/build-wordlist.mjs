// Usage: node scripts/build-wordlist.mjs <path-to-sv.csv>
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const SOURCE_URL =
  'https://huggingface.co/datasets/codesue/kelly/resolve/main/sv.csv'
const OUT = new URL('../src/content/beginner/words.ts', import.meta.url)
const CEFR = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2']

function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"'
        i++
      } else if (c === '"') quoted = false
      else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') {
      row.push(field)
      field = ''
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++
      row.push(field)
      field = ''
      rows.push(row)
      row = []
    } else field += c
  }
  if (field !== '' || row.length) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

const path = process.argv[2]
if (!path) {
  console.error('Usage: node scripts/build-wordlist.mjs <path-to-sv.csv>')
  process.exit(1)
}

const [header, ...rows] = parseCsv(readFileSync(path, 'utf8'))
const col = (name) => header.indexOf(name)
const [iFreq, iLevel, iLemma] = ['Raw Frequency', 'CEFR Level', 'Lemma'].map(
  col,
)

const seen = new Set()
const entries = []
rows.forEach((r, order) => {
  const word = (r[iLemma] ?? '').trim()
  if (!/^[a-zåäö]+$/.test(word) || word.length > 12 || seen.has(word)) return
  seen.add(word)
  const level = CEFR.indexOf(r[iLevel])
  entries.push({
    word,
    level: level === -1 ? CEFR.length : level,
    freq: Number(r[iFreq]) || 0,
    order,
  })
})
entries.sort(
  (a, b) => a.level - b.level || b.freq - a.freq || a.order - b.order,
)

const header_ = `// Source: ${SOURCE_URL}
// Swedish Kelly list, Språkbanken, CC BY 4.0
// Generated by scripts/build-wordlist.mjs — do not edit.
`
const body = `export const WORDS: readonly string[] = ${JSON.stringify(entries.map((e) => e.word))}\n`
writeFileSync(OUT, header_ + body)
execFileSync('npx', ['prettier', '--write', OUT.pathname], { stdio: 'inherit' })
console.log(`Wrote ${entries.length} words`)
